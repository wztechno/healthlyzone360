#!/usr/bin/env node
/**
 * Regenerates the bundled-image manifest.
 *
 * Walks `assets/images/<family>/*.webp` and emits `src/media/image-manifest.generated.ts`: one
 * static `import` per file (Metro can only bundle an asset from a literal import/require, never a
 * computed path) and a `Record<key, ImageRequireSource>` keyed `"<family>/<basename>"`. The resolver
 * in `src/media/entity-image.tsx` turns a fixture `imagePlaceholderId` into one of these keys.
 *
 * The output is committed so the app needs no pre-build step; `--check` re-renders in memory and
 * exits non-zero if the committed file is stale, which is the drift guard `image-manifest.test.tsx`
 * also enforces.
 *
 * Usage: node scripts/build-image-manifest.mjs [--check]
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const imagesRoot = join(appRoot, 'assets', 'images');
const outFile = join(appRoot, 'src', 'media', 'image-manifest.generated.ts');

/** `<family>/<basename>` for every WebP under a family sub-directory, sorted for stable output. */
export async function collectImageKeys() {
    const entries = [];
    const families = (await readdir(imagesRoot, { withFileTypes: true }))
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
        .sort();

    for (const family of families) {
        const files = (await readdir(join(imagesRoot, family)))
            .filter((name) => name.endsWith('.webp'))
            .sort();
        for (const file of files) {
            entries.push({
                key: `${family}/${file.replace(/\.webp$/, '')}`,
                importPath: `../../assets/images/${family}/${file}`,
            });
        }
    }
    return entries;
}

/**
 * The credit line every image that *obliges* one must show, keyed by `<family>/<base>`.
 *
 * Read from `assets/images/provenance.json`, which the sourcing pipeline writes. Only entries whose
 * licence actually requires attribution are emitted: a public-domain photograph needs no visible
 * credit, so carrying one for every file would put several hundred dead entries in the bundle.
 *
 * Attribution is a licence condition, not a courtesy — CC BY and CC BY-SA ask for the creator, the
 * licence, a link to the source and a statement that the work was modified, and every file here is
 * cropped and re-encoded. All four travel together so a call site cannot render half of one.
 */
async function collectCredits() {
    let provenance;
    try {
        provenance = JSON.parse(
            await readFile(join(appRoot, 'assets', 'images', 'provenance.json'), 'utf8'),
        );
    } catch {
        return [];
    }

    return Object.entries(provenance.images ?? {})
        .filter(([, entry]) => entry.attribution_required)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([key, entry]) => ({
            key,
            creator: entry.creator ?? '',
            licence: entry.licence_short_name || entry.licence || '',
            licenceUrl: entry.licence_url ?? '',
            sourceUrl: entry.source_url ?? '',
            modifications: entry.modifications ?? '',
            // Which library the photograph came through. A credit that named the wrong one —
            // "via Wikimedia Commons" on a Flickr photograph — would be a false attribution.
            provider: entry.provider ?? 'wikimedia',
        }));
}

export async function renderManifest() {
    const entries = await collectImageKeys();
    const credits = await collectCredits();

    const banner = [
        '/*',
        ' * AUTOGENERATED by scripts/build-image-manifest.mjs — do not edit by hand.',
        ' * Source: apps/universal/assets/images/<family>/*.webp',
        ' *         apps/universal/assets/images/provenance.json (the credit lines)',
        ' * Regenerate: pnpm --filter universal build:images',
        ' * Bundled, same-origin assets only. Nothing here may reference a remote host.',
        ' */',
    ].join('\n');

    const imports = entries.map((entry, index) => `import img${index} from '${entry.importPath}';`);
    const record = entries.map((entry, index) => `    '${entry.key}': img${index},`);

    return [
        banner,
        '',
        "import type { ImageRequireSource } from 'react-native';",
        '',
        ...imports,
        '',
        '/** Fixture/marketing image key → bundled WebP asset. */',
        'export const IMAGE_ASSETS: Record<string, ImageRequireSource> = {',
        ...record,
        '};',
        '',
        '/** How many families and files the manifest was generated from — used by the drift test. */',
        `export const IMAGE_ASSET_COUNT = ${entries.length};`,
        '',
        '/** A credit a licence obliges us to display, as {@link PhotoCredit} renders it. */',
        'export interface ImageCredit {',
        '    readonly creator: string;',
        '    readonly licence: string;',
        '    readonly licenceUrl: string;',
        '    readonly sourceUrl: string;',
        '    readonly modifications: string;',
        '    readonly provider: string;',
        '}',
        '',
        '/**',
        ' * Images whose licence requires a visible credit, keyed `<family>/<base>` (no variant —',
        ' * a card and its detail crop come from one photograph and carry one credit).',
        ' *',
        ' * Public-domain and CC0 files are deliberately absent: they oblige nothing, so a lookup',
        ' * miss means "no credit required" rather than "credit missing".',
        ' */',
        'export const IMAGE_CREDITS: Record<string, ImageCredit> = {',
        ...credits.map(
            (credit) =>
                `    ${JSON.stringify(credit.key)}: { creator: ${JSON.stringify(credit.creator)}, ` +
                `licence: ${JSON.stringify(credit.licence)}, licenceUrl: ${JSON.stringify(credit.licenceUrl)}, ` +
                `sourceUrl: ${JSON.stringify(credit.sourceUrl)}, modifications: ${JSON.stringify(credit.modifications)}, ` +
                `provider: ${JSON.stringify(credit.provider)} },`,
        ),
        '};',
        '',
        '/** How many images oblige a visible credit — used by the drift test. */',
        `export const IMAGE_CREDIT_COUNT = ${credits.length};`,
        '',
    ].join('\n');
}

async function main() {
    const contents = await renderManifest();
    const check = process.argv.includes('--check');

    let existing = null;
    try {
        existing = await readFile(outFile, 'utf8');
    } catch {
        // First run.
    }

    if (existing === contents) {
        console.log(
            `unchanged  src/media/image-manifest.generated.ts (${IMAGE_ASSET_COUNT_from(contents)} assets)`,
        );
        return;
    }

    if (check) {
        console.error(
            'DRIFT  src/media/image-manifest.generated.ts is out of date. Run: pnpm --filter universal build:images',
        );
        process.exitCode = 1;
        return;
    }

    await writeFile(outFile, contents, 'utf8');
    console.log(
        `written    src/media/image-manifest.generated.ts (${IMAGE_ASSET_COUNT_from(contents)} assets)`,
    );
}

function IMAGE_ASSET_COUNT_from(contents) {
    return /IMAGE_ASSET_COUNT = (\d+)/.exec(contents)?.[1] ?? '?';
}

await main();
