/**
 * The name the workspace badge renders for each organisation this suite signs into.
 *
 * Needed because {@link selectOrganisation} has to be able to assert *which* workspace it ended up
 * in even when no choice was offered — see below — and the only thing on screen at that point is the
 * organisation's display name.
 */
const ORGANISATION_NAMES: Readonly<Record<string, string>> = {
    [VERDANT_SLUG]: 'Verdant Kitchen',
    [CEDAR_SLUG]: 'Cedar Clinic',
    [ACME_SLUG]: 'Acme Wellness',
};

export async function selectOrganisation(page: Page, slug: string): Promise<void> {
    const name = ORGANISATION_NAMES[slug];
    if (name === undefined) throw new Error(`No display name recorded for "${slug}".`);

    await page.goto('/select-organisation');

    const picker = page.getByTestId('organisation-picker-screen');
    const workspace = page.getByTestId('workspace-selector-screen');
    await expect(picker.or(workspace).first()).toBeVisible({ timeout: JOURNEY_TIMEOUT });

    /*
     * The picker only *offers* a choice when there is one to make.
     *
     * `organisation-picker-screen.tsx` auto-selects a person's only selectable membership and
     * replaces the route — it renders `organisation-picker-autoskip` for a moment and then the
     * workspace. Three of this suite's four staff personas hold exactly one membership
     * (`owner@verdant.test`, `owner@cedar.test`, `buyer@acme-wellness.test`), so for them there is
     * no `organisation-{slug}` control to press and waiting for one is waiting forever. Only
     * `dietitian@cedar.test` belongs to two organisations and therefore actually sees the list.
     *
     * Either way the assertion at the end is the same and is the one that matters: the workspace
     * this helper leaves the page in belongs to the organisation that was asked for.
     */
    if ((await page.getByTestId(`organisation-${slug}`).count()) > 0) {
        await page.getByTestId(`organisation-${slug}`).click();
    }

    await expect(workspace).toBeVisible({ timeout: JOURNEY_TIMEOUT });
    await expect(page.getByTestId('workspace-organisation')).toContainText(name, {
        timeout: JOURNEY_TIMEOUT,
    });
}

