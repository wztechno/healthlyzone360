/* ── talking to the API directly ─────────────────────────────────────────────────────────────── */

export interface ApiCallOptions {
    readonly token?: string | undefined;
    readonly headers?: Record<string, string> | undefined;
    readonly data?: unknown;
}

/**
 * A direct call to the API from the browser context, bypassing the UI.
 *
 * Used only for the things a UI cannot express: following a signed verification link, probing a
 * context the application would never claim, resolving an identifier the screens address by slug,
 * and confirming that a revoked token is really dead.
 */
export async function apiRequest(
    request: APIRequestContext,
    method: 'get' | 'post' | 'put' | 'patch' | 'delete',
    path: string,
    options: ApiCallOptions = {},
) {
    const headers: Record<string, string> = {
        Accept: 'application/json',
        'X-Client-Request-Id': `e2e-${String(Date.now())}`,
        ...(options.token === undefined ? {} : { Authorization: `Bearer ${options.token}` }),
        ...options.headers,
    };

    const url = path.startsWith('http') ? path : `${API_URL}${path}`;
    return request[method](url, {
        headers,
        ...(options.data === undefined ? {} : { data: options.data }),
    });
}

/** Exchanges credentials for a second, independent bearer token bound to its own device. */
export async function issueToken(
    request: APIRequestContext,
    email: string,
    deviceName: string,
    platform: 'web' | 'ios' | 'android' = 'android',
): Promise<{ token: string; deviceId: string }> {
    const response = await apiRequest(request, 'post', '/api/v1/auth/token', {
        data: { email, password: DEMO_PASSWORD, device_name: deviceName, platform },
    });
    expect(response.status(), await response.text()).toBe(201);

    const body = (await response.json()) as {
        data: { token: string; device: { id: string } };
    };
    return { token: body.data.token, deviceId: body.data.device.id };
}

/** The signed-in user's own identifier, straight from `/me`. */
export async function readUserId(request: APIRequestContext, token: string): Promise<string> {
    const response = await apiRequest(request, 'get', '/api/v1/me', { token });
    expect(response.status(), await response.text()).toBe(200);
    const body = (await response.json()) as { data: { user: { id: string } } };
    return body.data.user.id;
}

/* ── reading the mail the stack "sent" ───────────────────────────────────────────────────────── */

/**
 * The newest verification link the API has logged for a given needle.
 *
 * With no mail server, the rendered message is appended to the Laravel log, so this reads that file
 * instead of polling an inbox. It is polled rather than awaited on a hook because the mail is queued
 * and the queue worker is a separate process. Each entry is the full MIME message, quoted-printable
 * encoded.
 *
 * **The needle is the user's identifier, not their address**, and that is this stack's doing rather
 * than a preference: the mail logger redacts recipients (`To: a***@healthy360.test`), so correlating
 * by address matches nothing at all. The signed URL embeds the user id — `/verify-email/{id}/{hash}`
 * — which is both unambiguous and impossible to redact without breaking the link, so that is what
 * the entries are matched on. Any string may be passed; the id is simply the one that works here.
 */
export async function fetchVerificationLink(needle: string, attempts = 60): Promise<string> {
    for (let attempt = 0; attempt < attempts; attempt += 1) {
        let raw: string;
        try {
            raw = await readFile(MAIL_LOG, 'utf8');
        } catch {
            raw = '';
        }

        // Laravel log entries begin with a `[timestamp]` prefix; split so each block is one message.
        const entries = raw.split(/(?=^\[\d{4}-\d\d-\d\d[ T])/m);
        for (let index = entries.length - 1; index >= 0; index -= 1) {
            const decoded = decodeQuotedPrintable(entries[index] ?? '');
            if (!decoded.includes(needle)) continue;
            const link = extractVerificationLink(decoded);
            if (link !== null) return link;
        }

        await new Promise((settle) => setTimeout(settle, 500));
    }

    throw new Error(
        `No verification mail mentioning ${needle} was logged within ${String(attempts * 500)}ms ` +
            `(${MAIL_LOG}).`,
    );
}

/**
 * Undo the quoted-printable encoding the mail logger writes: soft line breaks (`=` at end of line)
 * are removed and `=XX` escapes decoded, so a signed URL split across lines becomes whole again.
 */
function decodeQuotedPrintable(body: string): string {
    return body
        .replace(/=\r?\n/g, '')
        .replace(/=([0-9A-Fa-f]{2})/g, (_, hex: string) => String.fromCharCode(parseInt(hex, 16)));
}

/**
 * The signed link out of the mail body.
 *
 * The HTML part contains the same URL with `&amp;` entities and, in the plain-text part, wrapped in
 * markdown brackets — so the match is trimmed of trailing punctuation and the entities decoded.
 */
export function extractVerificationLink(body: string): string | null {
    const match = /https?:\/\/[^\s"'<>]*verify-email[^\s"'<>)\]]*/.exec(body);
    if (match === null) return null;
    return match[0].replace(/&amp;/g, '&').replace(/[).,]+$/, '');
}

/* ── two-factor ──────────────────────────────────────────────────────────────────────────────── */

/** Base32 (RFC 4648, no padding) → bytes. Twenty lines, and it saves a dependency. */
function decodeBase32(secret: string): Buffer {
    const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
    let bits = '';
    for (const character of secret.replace(/=+$/, '').toUpperCase()) {
        const value = alphabet.indexOf(character);
        if (value === -1) throw new Error(`"${character}" is not a base32 digit.`);
        bits += value.toString(2).padStart(5, '0');
    }

    const bytes: number[] = [];
    for (let offset = 0; offset + 8 <= bits.length; offset += 8) {
        bytes.push(Number.parseInt(bits.slice(offset, offset + 8), 2));
    }
    return Buffer.from(bytes);
}

/**
 * A TOTP code for the seeded shared secret (RFC 6238: HMAC-SHA1, 30-second step, six digits).
 *
 * Implemented here rather than taken from a package because it is fifteen lines of `node:crypto`
 * and the alternative is a runtime dependency in a repository that has none for this — and because
 * a test that generates its own code proves the server's clock and the client's agree, which a
 * stubbed code would not.
 */
export function totpCode(secret: string = TWO_FACTOR_SECRET, at: number = Date.now()): string {
    const counter = Math.floor(at / 1000 / 30);
    const message = Buffer.alloc(8);
    message.writeBigUInt64BE(BigInt(counter));

    const digest = createHmac('sha1', decodeBase32(secret)).update(message).digest();
    const offset = (digest[digest.length - 1] as number) & 0x0f;
    const binary =
        (((digest[offset] as number) & 0x7f) << 24) |
        (((digest[offset + 1] as number) & 0xff) << 16) |
        (((digest[offset + 2] as number) & 0xff) << 8) |
        ((digest[offset + 3] as number) & 0xff);

    return String(binary % 1_000_000).padStart(6, '0');
}

