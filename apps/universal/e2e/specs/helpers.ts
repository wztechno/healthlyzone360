/** Where the web build keeps the bearer token (`src/session/storage.ts`). */
const SESSION_TOKEN_KEY = 'h360.session-token';

export interface StackStatus {
    readonly api: boolean;
    readonly mailLog: boolean;
    readonly reason: string;
}

async function reachable(url: string): Promise<boolean> {
    try {
        // Generous on purpose: the Windows Docker stack answers /up in ~5-6s cold (php-fpm over a
        // bind mount), and a probe that times out on a slow-but-alive stack skips the whole suite.
        const response = await fetch(url, { signal: AbortSignal.timeout(15_000) });
        return response.ok;
    } catch {
        return false;
    }
}

async function fileReadable(path: string): Promise<boolean> {
    try {
        await readFile(path);
        return true;
    } catch {
        return false;
    }
}

/**
 * Probes the stack once per file.
 *
 * A missing stack is not a failing test — it is a missing prerequisite — so a spec skips with an
 * instruction instead of timing out five times over. Mail is read from the API's log rather than a
 * mail server, so the "inbox" prerequisite is simply that the log file is readable.
 */
export async function probeStack(): Promise<StackStatus> {
    const [api, mailLog] = await Promise.all([reachable(`${API_URL}/up`), fileReadable(MAIL_LOG)]);

    const missing = [
        api ? null : `the API at ${API_URL}`,
        mailLog ? null : `a readable mail log at ${MAIL_LOG} (the API must have run at least once)`,
    ].filter((entry): entry is string => entry !== null);

    return {
        api,
        mailLog,
        reason:
            missing.length === 0
                ? ''
                : `These specs need ${missing.join(' and ')}. Start it with \`docker compose up -d --wait\`.`,
    };
}

export function skipUnlessStackIsUp(status: StackStatus, mailLogRequired = false): void {
    test.skip(!status.api || (mailLogRequired && !status.mailLog), status.reason);
}

/* ── signing in ──────────────────────────────────────────────────────────────────────────────── */

/**
 * How long a *chain* of round trips is allowed to take, as opposed to a single assertion.
 *
 * The project-wide `expect` timeout is 20 s, which is right for "this element should appear once its
 * data has arrived" — one request. Signing in is not one request: it is `POST /auth/login`, then
 * `GET /me`, then the landing resolver, then whichever screen that picks fetching its own data. On
 * the Windows Docker stack each leg answers in six to nine seconds (php-fpm over a bind mount), so
 * the chain routinely costs thirty and the assertion at the end of it was failing on a stack that
 * was working perfectly. Choosing an organisation is the same shape: `PUT /me/context`, a refetch of
 * `/me`, then the workspace's own reads.
 *
 * Raising the global budget instead would have hidden a genuinely stuck single request behind two
 * minutes of patience everywhere. This is deliberately narrow: it applies to the two helpers that
 * really do wait on several requests, and nowhere else.
 *
 * Two minutes looks extravagant and is not: it is a *ceiling*, paid only when something is wrong.
 * The observed cost of a sign-in on this stack is thirty to forty seconds idle and past seventy-five
 * when two workers are both mid-journey — the API container answers `/up` itself in five to eight
 * seconds — so a budget that merely covered the idle case failed on a stack that was working. On
 * CI's `artisan serve` the whole chain lands in well under a second and this number is never
 * approached.
 */
export const JOURNEY_TIMEOUT = 120_000;

/**
 * Somewhere authenticated, whichever of them this account lands on.
 *
 * Where a person lands is the *server's* decision and it differs per account: a consumer with no
 * membership goes to the customer home, somebody with two memberships and no remembered context
 * goes to the organisation picker, and anybody whose last workspace the API still remembers
 * (`user_profiles.last_organisation_id`) is routed straight past it to the workspace selector. All
 * three are "signed in", so all three are accepted.
 */
export function authenticatedLandmark(page: Page): Locator {
    return page
        .getByTestId('organisation-picker-screen')
        .or(page.getByTestId('workspace-selector-screen'))
        .or(page.getByTestId('branch-picker-screen'))
        .or(page.getByTestId('consumer-home-screen'))
        .first();
}

/**
 * Signs in through the real screen and waits until the session is genuinely established.
 *
 * Two waits, and the second is the one that was missing. The old helper waited for the sign-in
 * screen to be *hidden*, which the router satisfies the instant it starts replacing the route —
 * before the token has been written to storage. A `page.goto` issued immediately afterwards then
 * raced the write and landed on a signed-out screen, which on a slow stack looked exactly like an
 * application bug. So: wait for an authenticated landmark to paint, and then for the credential to
 * actually be in `localStorage`.
 */
export async function signIn(
    page: Page,
    email: string = CONSUMER_EMAIL,
    password: string = DEMO_PASSWORD,
): Promise<void> {
    /*
     * Attempted twice, and only for one specific failure — see `submitSignIn`.
     *
     * A sign-in that lands on the *anonymous* marketplace is not a slow sign-in and no amount of
     * waiting fixes it: the credential was accepted, `router.replace('/')` ran, and the home router
     * then resolved `unauthenticated` because the session had not become authenticated. Nothing in
     * the application retries from there, so the page sits on the public landing for as long as the
     * assertion is willing to wait. It is reproducible on this stack — see the note in
     * `submitSignIn` — and one clean re-attempt is what keeps a local run usable while it stands.
     */
    if (await submitSignIn(page, email, password)) return;
    if (await submitSignIn(page, email, password)) return;

    throw new Error(
        `Signing in as ${email} succeeded but the application settled on the anonymous ` +
            'marketplace landing, twice. The credential was accepted and the home router then ' +
            'resolved `unauthenticated`, which is what happens when the `GET /me` that follows ' +
            'sign-in does not land — the session machine has no retry from that state, so the ' +
            'page stays anonymous with a valid token in storage.',
    );
}

/**
 * One sign-in attempt. `true` when it reached an authenticated landmark.
 *
 * Returns `false` only for the anonymous-landing outcome above. Every other failure throws, because
 * every other failure is worth reporting rather than retrying: a refused credential is a finding, a
 * rate limit is a finding, and a landmark that simply never paints is a timeout with a call log
 * attached.
 */
async function submitSignIn(page: Page, email: string, password: string): Promise<boolean> {
    await page.goto('/sign-in');
    await expect(page.getByTestId('sign-in-screen')).toBeVisible();

    /*
     * Filled *and read back*, which is not belt-and-braces.
     *
     * The export hydrates after its first paint, and `sign-in-screen` is visible before the form
     * behind it is interactive: a `fill` that lands in that window writes into a node React then
     * replaces, and the submit that follows posts an empty form. That produced the most confusing
     * failure in this suite — a sign-in that "timed out" on a page whose email box was blank and
     * whose submit button was enabled and idle. Asserting the value is what makes the fill a fact
     * rather than an attempt.
     */
    const emailInput = page.getByTestId('sign-in-email').locator('input').first();
    const passwordInput = page.getByTestId('sign-in-password').locator('input').first();
    await emailInput.fill(email);
    await passwordInput.fill(password);
    await expect(emailInput).toHaveValue(email);
    await expect(passwordInput).toHaveValue(password);

    await page.getByTestId('sign-in-submit').click();

    /*
     * A refused credential is reported as a refusal rather than as a timeout. Without this, a rate
     * limit or a wrong password reads as "the landmark never appeared", which sends whoever is
     * debugging it to look at the wrong screen entirely.
     */
    /*
     * Three outcomes are waited for at once, because two of them are answers rather than delays.
     *
     * A refused credential is reported as a refusal: without this, a rate limit or a wrong password
     * reads as "the landmark never appeared", which sends whoever is debugging it to the wrong
     * screen entirely. And `landing-screen` — the *anonymous* marketplace — is the outcome
     * described above: an accepted credential whose session never became authenticated. No account
     * in this suite legitimately lands there, so seeing it is a result, not a wait.
     */
    const landmark = authenticatedLandmark(page);
    const refusal = page.getByTestId('sign-in-error');
    const anonymous = page.getByTestId('landing-screen');
    await expect(landmark.or(refusal).or(anonymous).first()).toBeVisible({
        timeout: JOURNEY_TIMEOUT,
    });

    if ((await refusal.count()) > 0) {
        throw new Error(`Signing in as ${email} was refused: ${await refusal.innerText()}`);
    }
    if ((await landmark.count()) === 0) return false;

    await expect(landmark).toBeVisible({ timeout: JOURNEY_TIMEOUT });
    await expect
        .poll(
            async () =>
                page.evaluate((key) => globalThis.localStorage.getItem(key), SESSION_TOKEN_KEY),
            {
                message: 'the application should have persisted a bearer token',
                timeout: JOURNEY_TIMEOUT,
            },
        )
        .not.toBeNull();

    return true;
}

