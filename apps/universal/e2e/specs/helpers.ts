/**
 * Put one address in the signed-in account's book, through the two screens that own it.
 *
 * Checkout and the subscription record both take a delivery address by *identifier* (D-084) — the
 * zone, the window and the fee resolve from a saved entry — so neither offers a form to type into.
 * The seeded consumer starts with one saved address in Verdant's Al Quoz zone, so every journey in
 * this suite uses that one and nothing calls this helper today.
 *
 * It is kept, unused, because it is the only route to a *second* address and because deleting it
 * would hide a finding: against this stack the editor at `/customer/account/addresses/new` never
 * rendered its fields — `address-editor-label` was still absent after seven and a half minutes,
 * with the screen's chrome painted around nothing. That is worth fixing rather than forgetting, and
 * the journey that needed two addresses says so where it used to call this.
 *
 * Expects the page to already be on `/customer/account/addresses`, and leaves it there with the new
 * entry in the list. Driven entirely by test identifier, so it is direction- and locale-agnostic.
 */
export async function saveAddress(page: Page, label: string, line1: string): Promise<void> {
    await expect(page.getByTestId('addresses-screen')).toBeVisible();
    await page.getByTestId('addresses-screen-add').click();
    await expect(page.getByTestId('address-editor')).toBeVisible();

    await page.getByTestId('address-editor-label').locator('input').first().fill(label);
    // The area is a foreign key into the platform's service areas, so it is chosen, never typed.
    await page.getByTestId('address-editor-area-trigger').click();
    await page.locator('[data-testid^="address-editor-area-option-"]').first().click();
    await page.getByTestId('address-editor-line1').locator('input').first().fill(line1);
    await page.getByTestId('address-editor-save').click();

    // The save reached the server rather than merely the form: the list is showing again.
    await expect(page.getByTestId('addresses-screen-list')).toBeVisible();
}

/**
 * Empty the signed-in account's basket, so a journey starts from a state it can reason about.
 *
 * The basket is a real, persisted record now: a run that placed no order leaves its lines behind and
 * the next run would price a basket it did not fill. Expects to be on `/customer/cart`.
 */
export async function emptyBasket(page: Page): Promise<void> {
    await expect(page.getByTestId('cart-screen')).toBeVisible();

    const removes = page.locator('[data-testid$="-remove"]');

    for (let attempt = 0; attempt < 12; attempt += 1) {
        if ((await page.getByTestId('cart-empty').count()) > 0) return;

        const before = await removes.count();
        if (before === 0) return;

        /*
         * Enabled *then* clicked, and then waited on by count.
         *
         * Every control on a basket line is disabled while a mutation is in flight
         * (`busy={setQuantity.isPending || removeItem.isPending}` in `cart-screen.tsx`), which on
         * this stack is several seconds. A loop that pressed "remove" again immediately met a
         * disabled button, and Playwright's click retries it until the element is *enabled* — but
         * the re-render replaces the node, so the retry restarts on a detached element and the
         * whole thing spins until the test times out. That is what wedged the first run of
         * `web-write` for seven and a half minutes on one basket.
         *
         * Waiting for the row *count* to drop is the honest completion signal: it is the thing the
         * removal is for, and it cannot be satisfied by a button that merely became clickable again.
         */
        const first = removes.first();
        await expect(first).toBeEnabled();
        await first.click();
        await expect.poll(async () => removes.count()).toBeLessThan(before);
    }
}
